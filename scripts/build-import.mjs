#!/usr/bin/env node
// Generates the Base64 string for Dokploy: Compose service -> Advanced -> Import.
//
//   node scripts/build-import.mjs                          # catalogue default (${domain} / sslip.io)
//   node scripts/build-import.mjs --base-domain example.com
//   node scripts/build-import.mjs --base-domain example.com \
//     --headscale-host hs.example.com --headplane-host admin.example.com \
//     --magicdns-domain ts.example.com
//
// Output: dist/import-base64.txt (override with --out). The string contains
// no secrets: Dokploy generates them on the server when importing.

import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, relative, resolve } from "node:path";
import {
	REPO_ROOT,
	applyVariableOverrides,
	checkMagicDnsDomain,
	loadBlueprint,
	overridesFromArgs,
	parseArgs,
} from "./lib/blueprint.mjs";
import { encodeImport, processImport } from "./lib/dokploy.mjs";

const USAGE = `Usage: node scripts/build-import.mjs [--base-domain <domain>]
       [--headscale-host <host>] [--headplane-host <host>] [--magicdns-domain <domain>]
       [--out <file>] [--stdout]`;

function main() {
	const args = parseArgs(process.argv.slice(2), { booleans: ["stdout", "help"] });
	if (args.help) {
		console.log(USAGE);
		return;
	}

	const blueprint = loadBlueprint();
	const overrides = overridesFromArgs(args);
	const config = Object.keys(overrides).length
		? applyVariableOverrides(blueprint.config, overrides)
		: blueprint.config;

	const base64 = encodeImport({ compose: blueprint.compose, config });

	// Preview exactly what Dokploy would create, to catch mistakes before import.
	const preview = processImport(base64, {
		appName: "preview-headscale-headplane-abc123",
		serverIp: "203.0.113.10",
	});
	const hosts = Object.fromEntries(
		preview.template.domains.map((d) => [d.serviceName, d.host]),
	);
	const magicDns = preview.template.variables.magicdns_domain;
	const problem = checkMagicDnsDomain(hosts.headscale, magicDns);
	if (problem) throw new Error(`${problem} (${magicDns} vs ${hosts.headscale})`);

	if (args.stdout) {
		process.stdout.write(`${base64}\n`);
		return;
	}

	const out = resolve(REPO_ROOT, args.out ?? "dist/import-base64.txt");
	mkdirSync(dirname(out), { recursive: true });
	writeFileSync(out, `${base64}\n`);

	const generated = overrides.base_domain === undefined && !args["headscale-host"];
	console.log(`Wrote ${relative(process.cwd(), out)} (${base64.length} bytes)`);
	console.log(
		generated
			? "Domains: generated by Dokploy at import (<app>-<hash>-<server-ip>.sslip.io), e.g.:"
			: "Domains created by the import:",
	);
	console.log(`  Headscale  https://${hosts.headscale}`);
	console.log(`  Headplane  https://${hosts.headplane}/admin`);
	console.log(`  MagicDNS   *.${magicDns}`);
}

try {
	main();
} catch (error) {
	console.error(`error: ${error.message}`);
	console.error(USAGE);
	process.exit(1);
}
